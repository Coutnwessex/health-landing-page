function bindHealthFaqInteractions() {
  if (window.__healthFaqInteractionsBound) return;
  window.__healthFaqInteractionsBound = true;

  document.addEventListener(
    "click",
    (event) => {
      const question = event.target.closest(".health-faq-section .faq-question");
      if (!question) return;

      event.preventDefault();
      event.stopImmediatePropagation();
      const item = question.closest(".faq-item");
      if (!item) return;
      const isOpen = item.classList.toggle("open");
      question.setAttribute("aria-expanded", String(isOpen));
      if (isOpen) {
        window.dataLayer?.push({
          event: "faq_open",
          product: document.body.dataset.product || "health",
          question: question.textContent.trim(),
          language: getCurrentLang(),
        });
      }
    },
    true,
  );

  document.addEventListener(
    "keydown",
    (event) => {
      const question = event.target.closest(".health-faq-section .faq-question");
      if (!question) return;
      if (event.key !== "Enter" && event.key !== " ") return;

      event.preventDefault();
      event.stopImmediatePropagation();
      const item = question.closest(".faq-item");
      if (!item) return;
      const isOpen = item.classList.toggle("open");
      question.setAttribute("aria-expanded", String(isOpen));
      if (isOpen) {
        window.dataLayer?.push({
          event: "faq_open",
          product: document.body.dataset.product || "health",
          question: question.textContent.trim(),
          language: getCurrentLang(),
        });
      }
    },
    true,
  );
}

function bindHealthInteractions() {
  bindHealthFaqInteractions();

  document.querySelectorAll("[data-next-step]").forEach((link) => {
    link.addEventListener("click", (event) => {
      const target = document.getElementById(link.dataset.nextStep);
      if (!target) return;
      event.preventDefault();
      target.scrollIntoView({ behavior: "smooth", block: "start" });
    });
  });

  document.querySelectorAll("[data-review-carousel]").forEach((carousel) => {
    const cards = [...carousel.querySelectorAll("[data-review-card]")];
    const counter = carousel.querySelector("[data-review-count]");
    let activeIndex = 0;
    let leaveTimer = 0;
    let touchStartX = 0;
    let touchStartY = 0;
    let touchDeltaX = 0;
    let touchDeltaY = 0;
    const showCard = (nextIndex, direction = "next") => {
      const normalizedIndex = (nextIndex + cards.length) % cards.length;
      if (normalizedIndex === activeIndex) return;

      window.clearTimeout(leaveTimer);
      carousel.dataset.reviewDirection = direction;

      const previousCard = cards[activeIndex];
      cards.forEach((card) => card.classList.remove("is-leaving"));
      previousCard?.classList.add("is-leaving");
      previousCard?.classList.remove("active");

      activeIndex = normalizedIndex;
      cards.forEach((card, index) => card.classList.toggle("active", index === activeIndex));
      if (counter) counter.textContent = `${activeIndex + 1} / ${cards.length}`;

      leaveTimer = window.setTimeout(() => {
        previousCard?.classList.remove("is-leaving");
      }, 320);
    };
    carousel.querySelector("[data-review-prev]")?.addEventListener("click", () => showCard(activeIndex - 1, "prev"));
    carousel.querySelector("[data-review-next]")?.addEventListener("click", () => showCard(activeIndex + 1, "next"));
    carousel.addEventListener(
      "touchstart",
      (event) => {
        const touch = event.touches[0];
        touchStartX = touch.clientX;
        touchStartY = touch.clientY;
        touchDeltaX = 0;
        touchDeltaY = 0;
      },
      { passive: true },
    );
    carousel.addEventListener(
      "touchmove",
      (event) => {
        const touch = event.touches[0];
        touchDeltaX = touch.clientX - touchStartX;
        touchDeltaY = touch.clientY - touchStartY;
      },
      { passive: true },
    );
    carousel.addEventListener("touchend", () => {
      const isHorizontalSwipe = Math.abs(touchDeltaX) > 48 && Math.abs(touchDeltaX) > Math.abs(touchDeltaY) * 1.3;
      if (!isHorizontalSwipe) return;
      showCard(activeIndex + (touchDeltaX < 0 ? 1 : -1), touchDeltaX < 0 ? "next" : "prev");
    });
  });

  document.querySelectorAll("[data-tariffs-open]").forEach((button) => {
    button.addEventListener("click", openTariffDialog);
  });
  document.querySelector("[data-tariffs-close]")?.addEventListener("click", closeTariffDialog);
  document.getElementById("tariffDialog")?.addEventListener("click", (event) => {
    if (event.target === event.currentTarget) closeTariffDialog();
  });

}

function openTariffDialog() {
  const dialog = document.getElementById("tariffDialog");
  if (!dialog) return;
  dialog.classList.add("open");
  dialog.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
  window.dataLayer?.push({
    event: "health_tariffs_open",
    product: "health",
    location: "tariff_dialog",
    language: getCurrentLang(),
  });
  dialog.querySelector("[data-tariffs-close]")?.focus();
}

function closeTariffDialog() {
  const dialog = document.getElementById("tariffDialog");
  if (!dialog) return;
  dialog.classList.remove("open");
  dialog.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
}

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeTariffDialog();
});

